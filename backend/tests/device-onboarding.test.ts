import 'dotenv/config';
import { afterAll, expect, it } from 'vitest';
import request from 'supertest';
import { randomUUID } from 'node:crypto';
import { execFile } from 'node:child_process';
import { promisify } from 'node:util';
import { resolve } from 'node:path';
import { createApp } from '../src/app.js';
import { db } from '../src/lib/db.js';

const app = createApp();
const emails: string[] = [];
const account = () => request.agent(app);
type Client = ReturnType<typeof account>;
async function post(client: Client, path: string, body: object = {}, bearer?: string) {
  const csrf = (await client.get('/api/auth/csrf')).body.data.token;
  return client
    .post(path)
    .set('x-csrf-token', csrf)
    .set('Authorization', bearer ? `Bearer ${bearer}` : '')
    .send(body);
}
afterAll(async () => {
  // Only identities generated by this exact test can be removed.
  if (emails.length) await db.user.deleteMany({ where: { email: { in: emails } } });
  await db.$disconnect();
});

it('onboards two isolated users with real observations and switches owned device profiles', async () => {
  const detected = await promisify(execFile)(
    resolve(
      'backend/local-agent/.venv',
      process.platform === 'win32' ? 'Scripts/python.exe' : 'bin/python',
    ),
    [
      '-c',
      'import json; from corewise_runner.detection import detect; from corewise_runner.telemetry import sample; print(json.dumps({"environment":detect(probe_gpu=False),"sample":sample()}))',
    ],
    { env: { ...process.env, PYTHONPATH: resolve('backend/local-agent') }, timeout: 15000 },
  );
  const observations = JSON.parse(detected.stdout);
  const a = account(),
    b = account();
  for (const user of [a, b]) {
    const email = `device-test-${randomUUID()}@example.invalid`;
    emails.push(email);
    expect(
      (
        await post(user, '/api/auth/register', {
          name: 'Isolated device integration test',
          email,
          password: 'temporary device test passphrase 2026',
        })
      ).status,
    ).toBe(201);
  }
  async function pair(owner: Client) {
    const code = (await post(owner, '/api/benchmarks/pairing')).body.data.code;
    const runner = account();
    const redeem = await post(runner, '/api/agent/redeem', {
      code,
      name: 'Actual host test pairing',
      environment: observations.environment,
      registerHardware: true,
    });
    expect(redeem.status).toBe(201);
    expect(
      (
        await post(runner, '/api/agent/redeem', {
          code,
          name: 'Replay',
          environment: observations.environment,
        })
      ).status,
    ).toBe(401);
    expect((await post(runner, '/api/agent/session', {}, redeem.body.data.token)).status).toBe(200);
    const profile = (await owner.get('/api/hardware-profiles')).body.data.find(
      (p: { detectionSnapshot?: { agentId: string } }) =>
        p.detectionSnapshot?.agentId === redeem.body.data.agentId,
    );
    expect(profile.cpuName).toBe(observations.environment.cpuModel);
    expect(profile.ramGb).toBe(observations.environment.totalRamBytes / 2 ** 30);
    expect((await owner.get('/api/auth/me')).body.data.selectedProfileId).toBe(profile.id);
    return { runner, profile, id: redeem.body.data.agentId };
  }
  const first = await pair(a),
    second = await pair(b),
    another = await pair(a);
  expect((await a.get('/api/benchmarks/agents')).body.data).toHaveLength(2);
  expect((await b.get('/api/benchmarks/agents')).body.data).toHaveLength(1);
  expect((await b.get(`/api/hardware-profiles/${first.profile.id}`)).status).toBe(404);
  expect((await post(b, `/api/hardware-profiles/${first.profile.id}/select`)).status).toBe(404);
  expect((await first.runner.get('/api/hardware/connection')).status).toBe(401);
  expect((await first.runner.post('/api/agent/telemetry').send(observations.sample)).status).toBe(
    403,
  );
  expect((await post(first.runner, '/api/agent/telemetry', observations.sample)).status).toBe(200);
  expect((await post(second.runner, '/api/agent/telemetry', observations.sample)).status).toBe(200);
  expect((await post(a, `/api/hardware-profiles/${first.profile.id}/select`)).status).toBe(204);
  const own = (await a.get('/api/hardware/connection')).body.data;
  expect(own.selectedAgentId).toBe(first.id);
  expect(own.agents.find((device: { id: string }) => device.id === first.id).status).toBe('FRESH');
  const other = (await b.get('/api/hardware/connection')).body.data;
  expect(other.selectedAgentId).toBe(second.id);
  expect(other.agents.map((d: { id: string }) => d.id)).toEqual([second.id]);
  expect((await post(a, `/api/hardware-profiles/${another.profile.id}/select`)).status).toBe(204);
  expect((await a.get('/api/hardware/connection')).body.data.selectedAgentId).toBe(another.id);
  expect((await post(b, `/api/benchmarks/agents/${first.id}/revoke`)).status).toBe(404);
  expect((await post(a, `/api/benchmarks/agents/${first.id}/revoke`)).status).toBe(204);
  expect((await post(first.runner, '/api/agent/telemetry', observations.sample)).status).toBe(401);
  expect((await a.get('/api/hardware-profiles')).body.data).toHaveLength(2);
}, 30000);
